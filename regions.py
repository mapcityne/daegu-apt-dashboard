@lru_cache(maxsize=1)
def regions() -> pd.DataFrame:
    """sggcd, sggnm, sidocd, sidonm, lat, lon, 시도(짧은 이름), 지역명(표시용)."""
    r = pd.read_csv(REGIONS_CSV, dtype={"sggcd": str, "sidocd": str})
    r["시도"] = r["sidocd"].map(SIDO_SHORT)
    r["지역명"] = r["시도"] + " " + r["sggnm"]
    return r


def sgg_name(code: str) -> str:
    r = regions().set_index("sggcd")
    return r.at[code, "지역명"] if code in r.index else code
